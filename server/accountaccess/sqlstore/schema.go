func ensureTimeout(ctx context.Context, tx *sqlx.Tx, isPostgres bool) error {
	unixType := "INTEGER"
	if isPostgres {
		unixType = "BIGINT"
	}
	columns := []struct {
		name       string
		definition string
	}{
		{name: "timeout_until_unix", definition: unixType + " NOT NULL DEFAULT 0"},
		{name: "timeout_reason", definition: "TEXT NOT NULL DEFAULT ''"},
	}
	for _, column := range columns {
		query := `ALTER TABLE account_access ADD COLUMN IF NOT EXISTS ` + column.name + " " + column.definition
		if !isPostgres {
			var count int
			err := tx.GetContext(ctx, &count, `SELECT COUNT(*) FROM pragma_table_info('account_access') WHERE name = ?`, column.name)
			if err != nil {
				return fmt.Errorf("timeoutColumn[%s]: %w", column.name, err)
			}
			if count != 0 {
				continue
			}
			query = `ALTER TABLE account_access ADD COLUMN ` + column.name + " " + column.definition
		}
		result, err := tx.ExecContext(ctx, query)
		if err != nil {
			return fmt.Errorf("timeoutAlter[%s]: %w", column.name, err)
		}
		if result == nil {
			return errors.New("timeout column migration returned no result")
		}
	}
	return nil
}
