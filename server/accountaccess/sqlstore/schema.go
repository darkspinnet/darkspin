// EnsureSchema runs after profile migrations. Backfill never promotes an account
// and never overwrites an existing ban, permission, or credential revision.
func (e *Store) EnsureSchema(ctx context.Context) error {
	if ctx == nil {
		return errors.New("nil context")
	}
	if e.db == nil {
		return errors.New("nil database")
	}
	tx, err := e.db.BeginTxx(ctx, nil)
	if err != nil {
		return fmt.Errorf("schemaBegin: %w", err)
	}
	defer rollback(tx)
	if e.isPostgres {
		result, lockErr := tx.ExecContext(ctx, `SELECT pg_advisory_xact_lock(1936748398, 1)`)
		if lockErr != nil {
			return fmt.Errorf("schemaLock: %w", lockErr)
		}
		if result == nil {
			return errors.New("schema lock returned no result")
		}
	}
	statements := sqliteSchemaStatements
	if e.isPostgres {
		statements = postgresSchemaStatements
	}
	for index, statement := range statements {
		result, execErr := tx.ExecContext(ctx, statement)
		if execErr != nil {
			return fmt.Errorf("schemaCreate[%d]: %w", index, execErr)
		}
		// DDL does not have a meaningful affected-row count.
		if result == nil {
			return errors.New("schema creation returned no result")
		}
	}
	err = ensureBanReason(ctx, tx, e.isPostgres)
	if err != nil {
		return fmt.Errorf("schemaBan: %w", err)
	}
	err = ensureIPLimit(ctx, tx, e.isPostgres)
	if err != nil {
		return fmt.Errorf("schemaIPLimit: %w", err)
	}
	err = ensureTimeout(ctx, tx, e.isPostgres)
	if err != nil {
		return fmt.Errorf("schemaTimeout: %w", err)
	}
	result, err := tx.ExecContext(ctx, `INSERT INTO account_access (user_id)
		SELECT id FROM "user" WHERE 1 = 1 ON CONFLICT (user_id) DO NOTHING`)
	if err != nil {
		return fmt.Errorf("schemaBackfill: %w", err)
	}
	if result == nil {
		return errors.New("access backfill returned no result")
	}
	err = tx.Commit()
	if err != nil {
		return fmt.Errorf("schemaCommit: %w", err)
	}
	return nil
}

// InitializeUser joins the profile creator's transaction so every committed new
// profile starts unprivileged. It must not be used to repair missing access rows
// during authentication; those reads intentionally fail closed.
func (e *Store) InitializeUser(ctx context.Context, tx *sqlx.Tx, userID int64) error {
	if ctx == nil {
		return errors.New("nil context")
	}
	if tx == nil || userID <= 0 {
		return errors.New("invalid account initialization")
	}
	result, err := tx.ExecContext(ctx, tx.Rebind(`INSERT INTO account_access (user_id) VALUES (?)`), userID)
	if err != nil {
		return fmt.Errorf("initializeInsert: %w", err)
	}
	affected, err := result.RowsAffected()
	if err != nil {
		return fmt.Errorf("initializeAffected: %w", err)
	}
	if affected != 1 {
		return errors.New("account initialization did not create one access record")
	}
	return nil
}

var sqliteSchemaStatements = []string{
	`CREATE TABLE IF NOT EXISTS account_access (
		user_id INTEGER PRIMARY KEY REFERENCES "user"(id) ON DELETE CASCADE,
		status INTEGER NOT NULL DEFAULT 0 CHECK (status >= 0),
		is_banned INTEGER NOT NULL DEFAULT 0 CHECK (is_banned IN (0, 1)),
		ban_reason TEXT NOT NULL DEFAULT '',
		timeout_until_unix INTEGER NOT NULL DEFAULT 0,
		timeout_reason TEXT NOT NULL DEFAULT '',
		ip_limit TEXT NOT NULL DEFAULT '',
		revision INTEGER NOT NULL DEFAULT 1 CHECK (revision > 0)
	)`,
	`CREATE TABLE IF NOT EXISTS admin_event (
		id INTEGER PRIMARY KEY AUTOINCREMENT,
		actor_type TEXT NOT NULL,
		actor_user_id INTEGER,
		target_user_id INTEGER,
		action TEXT NOT NULL,
		occurred_at_unix INTEGER NOT NULL,
		before_detail TEXT NOT NULL,
		after_detail TEXT NOT NULL,
		reason TEXT NOT NULL,
		operation_id TEXT NOT NULL,
		outcome TEXT NOT NULL
	)`,
	`CREATE INDEX IF NOT EXISTS admin_event_time ON admin_event (occurred_at_unix, id)`,
	`CREATE INDEX IF NOT EXISTS admin_event_target ON admin_event (target_user_id, id)`,
	`CREATE INDEX IF NOT EXISTS admin_event_operation ON admin_event (operation_id, id)`,
}

// Audit account IDs intentionally have no cascading foreign keys: history must
// survive deletion, and local/system actors do not have an account ID.
var postgresSchemaStatements = []string{
	`CREATE TABLE IF NOT EXISTS account_access (
		user_id BIGINT PRIMARY KEY REFERENCES "user"(id) ON DELETE CASCADE,
		status BIGINT NOT NULL DEFAULT 0 CHECK (status >= 0),
		is_banned BIGINT NOT NULL DEFAULT 0 CHECK (is_banned IN (0, 1)),
		ban_reason TEXT NOT NULL DEFAULT '',
		timeout_until_unix BIGINT NOT NULL DEFAULT 0,
		timeout_reason TEXT NOT NULL DEFAULT '',
		ip_limit TEXT NOT NULL DEFAULT '',
		revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0)
	)`,
	`CREATE TABLE IF NOT EXISTS admin_event (
		id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		actor_type TEXT NOT NULL,
		actor_user_id BIGINT,
		target_user_id BIGINT,
		action TEXT NOT NULL,
		occurred_at_unix BIGINT NOT NULL,
		before_detail TEXT NOT NULL,
		after_detail TEXT NOT NULL,
		reason TEXT NOT NULL,
		operation_id TEXT NOT NULL,
		outcome TEXT NOT NULL
	)`,
	`CREATE INDEX IF NOT EXISTS admin_event_time ON admin_event (occurred_at_unix, id)`,
	`CREATE INDEX IF NOT EXISTS admin_event_target ON admin_event (target_user_id, id)`,
	`CREATE INDEX IF NOT EXISTS admin_event_operation ON admin_event (operation_id, id)`,
}

func ensureBanReason(ctx context.Context, tx *sqlx.Tx, isPostgres bool) error {
	query := `ALTER TABLE account_access ADD COLUMN IF NOT EXISTS ban_reason TEXT NOT NULL DEFAULT ''`
	if !isPostgres {
		var count int
		err := tx.GetContext(ctx, &count, `SELECT COUNT(*) FROM pragma_table_info('account_access') WHERE name = 'ban_reason'`)
		if err != nil {
			return fmt.Errorf("banColumn: %w", err)
		}
		if count != 0 {
			return nil
		}
		query = `ALTER TABLE account_access ADD COLUMN ban_reason TEXT NOT NULL DEFAULT ''`
	}
	result, err := tx.ExecContext(ctx, query)
	if err != nil {
		return fmt.Errorf("banAlter: %w", err)
	}
	if result == nil {
		return errors.New("ban column migration returned no result")
	}
	return nil
}

